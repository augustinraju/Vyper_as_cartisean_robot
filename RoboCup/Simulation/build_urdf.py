"""Generate vyper.urdf from vyper.urdf.xacro with joint limits taken from the printer.

The prismatic joint limits are not written in the xacro file: they are the printer's
firmware limits (Marlin/Configuration*.h, read by Translation/sim_to_printer.py)
converted to sim joint values with the same AxisMaps the printer bridge uses. Changing
the firmware config or the calibration in sim_to_printer.py therefore changes the sim's
reachable range too.

simulation_gui.py and plan_gripper_move.py call build() at startup; run it by hand to
just regenerate the file (needs `pip install xacro`):
    python build_urdf.py
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
XACRO_FILE = os.path.join(HERE, "vyper.urdf.xacro")
URDF_FILE = os.path.join(HERE, "vyper.urdf")

sys.path.insert(0, os.path.join(HERE, "..", "Translation"))
from sim_to_printer import DEFAULT, SimToPrinter  # noqa: E402

HEADER = ("\n  GENERATED by build_urdf.py from vyper.urdf.xacro - do not edit by hand.\n"
          "  Joint limits come from the printer firmware via sim_to_printer.py.\n")


def joint_limits(transform: SimToPrinter = DEFAULT) -> dict[str, str]:
    """xacro args {x,y,z}_{lower,upper}: printer [min_mm, max_mm] as sim joint values [m]."""
    args = {}
    for name, axis in (("x", transform.x), ("y", transform.y), ("z", transform.z)):
        lo, hi = sorted((axis.to_sim(axis.min_mm), axis.to_sim(axis.max_mm)))
        # 6 significant digits = micrometre resolution, hides float noise (-0.09050000001)
        args[f"{name}_lower"], args[f"{name}_upper"] = f"{lo:.6g}", f"{hi:.6g}"
    return args


def build(out: str = URDF_FILE, transform: SimToPrinter = DEFAULT) -> str:
    """Render the xacro to `out` (rewritten only if its content changed); returns `out`."""
    try:
        import xacro
    except ImportError:
        raise SystemExit("xacro is not installed: pip install xacro") from None
    doc = xacro.process_file(XACRO_FILE, mappings=joint_limits(transform))
    doc.insertBefore(doc.createComment(HEADER), doc.documentElement)
    xml = doc.toprettyxml(indent="  ")
    try:
        with open(out, encoding="utf-8") as f:
            if f.read() == xml:
                return out
    except FileNotFoundError:
        pass
    with open(out, "w", encoding="utf-8") as f:
        f.write(xml)
    return out


if __name__ == "__main__":
    for k, v in joint_limits().items():
        print(f"{k:8s} = {v} m")
    print(f"wrote {build()}")
